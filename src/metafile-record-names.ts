function parse(list: string, prefix: string, hex: boolean): Map<number, string> {
	const map = new Map<number, string>();
	for (const entry of list.split(/\s+/)) {
		const colon = entry.indexOf(':');
		if (colon > 0) {
			map.set(hex ? parseInt(entry.slice(0, colon), 16) : Number(entry.slice(0, colon)), prefix + entry.slice(colon + 1));
		}
	}
	return map;
}

/** Name tables by record type: EMF (`EMR_*`), WMF (`META_*`) and EMF+ (`EMFPLUS_*`). */
export function recordNameTables(): { emr: Map<number, string>; meta: Map<number, string>; plus: Map<number, string> } {
	return { emr: parse(EMR, 'EMR_', false), meta: parse(META, 'META_', true), plus: parse(PLUS, 'EMFPLUS_', true) };
}
